import { execFileSync } from "node:child_process"
import { writeFileSync } from "node:fs"
import { buildSeedPlan } from "@/db/seed/plan-data"
import { CareerCode, CorrelativePurpose, CorrelativeType } from "@/types/enums"

const PLANS: ReadonlyArray<{ plan: string; code: CareerCode }> = [
  { plan: "2008", code: CareerCode.SistemasPlan2008 },
  { plan: "2023", code: CareerCode.Sistemas },
]

function exportPlan(code: CareerCode) {
  const plan = buildSeedPlan()
  return plan.subjects
    .filter((subject) => subject.careerCode === code)
    .map((subject) => {
      const rules = plan.correlatives.filter((rule) => rule.careerCode === code && rule.subjectNumber === subject.number)
      const required = (purpose: CorrelativePurpose, type?: CorrelativeType) =>
        rules
          .filter((rule) => rule.purpose === purpose && (type === undefined || rule.requirementType === type))
          .map((rule) => rule.requiredNumber)
          .sort((a, b) => a - b)
      return {
        number: subject.number,
        name: subject.name,
        level: subject.level,
        isElective: subject.isElective,
        regularToTake: required(CorrelativePurpose.Cursar, CorrelativeType.Regulares),
        approvedToTake: required(CorrelativePurpose.Cursar, CorrelativeType.Aprobadas),
        approvedToSit: required(CorrelativePurpose.Rendir),
      }
    })
}

function main(): void {
  const outputPath = process.argv[2]
  if (!outputPath) throw new Error("Usage: node --import tsx scripts/export-catalog.ts <output.ts>")
  const commit = execFileSync("git", ["rev-parse", "HEAD"], { encoding: "utf8" }).trim()
  const plans = PLANS.map(({ plan, code }) => `    "${plan}": [\n${exportPlan(code).map((subject) => `        ${JSON.stringify(subject)}`).join(",\n")},\n    ]`)
  const lines = [
    "// Generated by scripts/export-catalog.ts of https://github.com/FranprzDev/AdHorarium. Do not edit by hand.",
    `export const PLAN_DATA_SOURCE = { repository: "https://github.com/FranprzDev/AdHorarium", commit: "${commit}" } as const`,
    "",
    "export interface PlanSubject {",
    "    number: number;",
    "    name: string;",
    "    level: number;",
    "    isElective: boolean;",
    "    regularToTake: number[];",
    "    approvedToTake: number[];",
    "    approvedToSit: number[];",
    "}",
    "",
    `export const SISTEMAS_PLANS: Record<string, PlanSubject[]> = {\n${plans.join(",\n")},\n};`,
    "",
  ]
  writeFileSync(outputPath, lines.join("\n"))
}

main()
